//! Canonical Compose YAML. The output is a pure function of a validated
//! project, its revision and its slot. Every scalar is either a fixed token,
//! an integer, a boolean or a double-quoted string whose characters
//! validation already restricted, so no YAML escaping, anchors, tags, merge
//! keys or interpolation can appear.

use std::fmt::Write;

use super::layout::{compose_project, loopback_port, network_name, secret_file, volume_name};
use super::manifest::{PLATFORM, Project};

pub const REVISION_LABEL: &str = "org.arxcovo.revision";
pub const PROJECT_LABEL: &str = "org.arxcovo.project";
pub const VOLUME_LABEL: &str = "org.arxcovo.volume";
const NETWORK_KEY: &str = "arx-project";

pub fn render(project: &Project, revision: u64, slot: u8) -> String {
    let manifest = project.manifest();
    let id = manifest.project_id.as_str();
    let mut out = String::with_capacity(4096);
    out.push_str("# Generated by arx-guest from a validated project. Layout v1.\n");
    line(&mut out, format_args!("name: \"{}\"", compose_project(id)));
    out.push_str("services:\n");
    for (index, service) in manifest.services.iter().enumerate() {
        line(&mut out, format_args!("  \"{}\":", service.name));
        line(&mut out, format_args!("    image: \"{}\"", service.image));
        line(&mut out, format_args!("    platform: \"{PLATFORM}\""));
        line(
            &mut out,
            format_args!("    user: \"{}:{}\"", service.uid, service.gid),
        );
        line(
            &mut out,
            format_args!("    read_only: {}", service.read_only_rootfs),
        );
        out.push_str("    privileged: false\n");
        out.push_str("    restart: \"no\"\n");
        out.push_str("    ipc: \"private\"\n");
        out.push_str("    security_opt:\n      - \"no-new-privileges:true\"\n");
        out.push_str("    cap_drop:\n      - \"ALL\"\n");
        let limits = service.limits;
        line(
            &mut out,
            format_args!(
                "    cpus: \"{}.{:03}\"",
                limits.cpu_millis / 1000,
                limits.cpu_millis % 1000
            ),
        );
        line(
            &mut out,
            format_args!("    mem_limit: \"{}m\"", limits.memory_mib),
        );
        line(&mut out, format_args!("    pids_limit: {}", limits.pids));
        if !service.environment.is_empty() {
            let mut environment: Vec<_> = service.environment.iter().collect();
            environment.sort_by(|a, b| a.name.cmp(&b.name));
            out.push_str("    environment:\n");
            for var in environment {
                line(
                    &mut out,
                    format_args!("      \"{}\": \"{}\"", var.name, var.value),
                );
            }
        }
        if let Some(port) = service.http_port {
            out.push_str("    ports:\n");
            line(
                &mut out,
                format_args!(
                    "      - \"127.0.0.1:{}:{port}/tcp\"",
                    loopback_port(slot, index)
                ),
            );
        }
        line(
            &mut out,
            format_args!("    networks:\n      - \"{NETWORK_KEY}\""),
        );
        if !service.mounts.is_empty() {
            out.push_str("    volumes:\n");
            for mount in &service.mounts {
                out.push_str("      - type: \"volume\"\n");
                line(
                    &mut out,
                    format_args!("        source: \"{}\"", volume_name(id, &mount.volume)),
                );
                line(
                    &mut out,
                    format_args!("        target: \"{}\"", mount.target),
                );
                line(
                    &mut out,
                    format_args!("        read_only: {}", mount.read_only),
                );
                out.push_str("        volume:\n          nocopy: true\n");
            }
        }
        if !service.secrets.is_empty() {
            out.push_str("    secrets:\n");
            for slot_name in &service.secrets {
                line(&mut out, format_args!("      - source: \"{slot_name}\""));
                line(
                    &mut out,
                    format_args!("        target: \"/run/secrets/{slot_name}\""),
                );
            }
        }
        out.push_str("    labels:\n");
        line(
            &mut out,
            format_args!("      \"{PROJECT_LABEL}\": \"{id}\""),
        );
        line(
            &mut out,
            format_args!("      \"{REVISION_LABEL}\": \"{revision}\""),
        );
        // A secret-bearing service keeps no raw container log at all.
        if service.secrets.is_empty() {
            out.push_str(
                "    logging:\n      driver: \"local\"\n      options:\n        max-size: \"1m\"\n        max-file: \"2\"\n",
            );
        } else {
            out.push_str("    logging:\n      driver: \"none\"\n");
        }
    }
    out.push_str("networks:\n");
    line(&mut out, format_args!("  \"{NETWORK_KEY}\":"));
    line(&mut out, format_args!("    name: \"{}\"", network_name(id)));
    out.push_str("    driver: \"bridge\"\n");
    if !manifest.volumes.is_empty() {
        out.push_str("volumes:\n");
        for volume in &manifest.volumes {
            let name = volume_name(id, &volume.name);
            line(&mut out, format_args!("  \"{name}\":"));
            out.push_str("    external: true\n");
            line(&mut out, format_args!("    name: \"{name}\""));
        }
    }
    if !manifest.secrets.is_empty() {
        out.push_str("secrets:\n");
        for slot_name in &manifest.secrets {
            line(&mut out, format_args!("  \"{slot_name}\":"));
            line(
                &mut out,
                format_args!("    file: \"{}\"", secret_file(id, slot_name)),
            );
        }
    }
    out
}

fn line(out: &mut String, args: std::fmt::Arguments<'_>) {
    // Writing to a String cannot fail.
    let _ = out.write_fmt(args);
    out.push('\n');
}
